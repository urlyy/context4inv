"""Select the enabled candidate stages and pass their verified conjunction onward."""

import json

from nodes.artifacts import loop_directory
from nodes.config import read_experiment_options
from nodes.generation import STAGE_LOG_FILES
from nodes.state import WorkflowState


def merge_invariants(state: WorkflowState, config) -> WorkflowState:
    options = read_experiment_options(config)
    if options.joint_enabled:
        invariants = set(state["joint"]["verified_invariants"])
        stages = ("joint",)
    else:
        invariants = set().union(*state["per_variable"]["verified_invariants"].values())
        invariants.update(state["combined"]["verified_invariants"])
        stages = ("per_variable", "combined")
    if not invariants:
        raise ValueError("No valid invariants generated by the preliminary tasks")
    folder = loop_directory(config, state["function"]["name"], state["loop"]["index"])
    for stage in stages:
        messages = state[stage]["messages"]
        (folder / STAGE_LOG_FILES[stage]).write_text(
            "\n".join(message.pretty_repr() for message in messages),
            encoding="utf-8",
        )
    (folder / "invariants_pre.json").write_text(
        json.dumps(sorted(invariants)), encoding="utf-8"
    )
    return {"postcondition": {"verified_invariants": invariants}}
